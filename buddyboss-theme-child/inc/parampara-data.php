/** Parampara for a profile slug; sampradayas fall back to their founder. */
function sp_parampara_for( $slug ) {
    $all = sp_parampara_data_all();
    if ( isset( $all[ $slug ] ) ) {
        return $all[ $slug ];
    }
    $data = function_exists( 'sp_dharma_data_all' ) ? ( sp_dharma_data_all()[ $slug ] ?? null ) : null;
    if ( ! $data || 'sampradaya' !== ( $data['kind'] ?? '' ) || empty( $data['infobox']['Founder'] ) ) {
        return null;
    }
    return array(
        'founder' => array( 'name' => $data['infobox']['Founder'], 'when' => '', 'note' => '' ),
        'basis'   => 'documented',
        'count'   => 'The line of Acharyas is being compiled',
        'nodes'   => array(
            array( 'name' => 'Line of Acharyas', 'period' => 'Being compiled and verified', 'gap' => true ),
        ),
    );
}
